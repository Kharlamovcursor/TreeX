@Composable
fun HelpSection(title: String, lines: List<String>) {
    Text(title, color = HdTextPrimary, fontWeight = FontWeight.SemiBold, modifier = Modifier.padding(top = 12.dp))
    lines.forEach { line ->
        Text(line, color = HdTextSecondary, modifier = Modifier.padding(top = 6.dp))
    }
}
